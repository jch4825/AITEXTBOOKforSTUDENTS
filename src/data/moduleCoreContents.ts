import type { ModuleId } from '../types';

/**
 * 단원별 핵심 내용의 단일 진실 원천.
 *
 * 2022 개정 특수교육 기본 교육과정의 각 교과는 '내용 체계'만 제시하지 않고
 * 무엇을 어떤 순서로 다루는지 이어서 밝힌다. 이 과목의 교사 화면에는 그동안
 * 영역별 내용 체계표까지만 있어서, 한 단원이 실제로 어떤 내용을 어떤 차시
 * 묶음으로 다루는지 문서로 확인할 길이 없었다.
 *
 * 여기 적는 문장은 서술 형식만 기본 교육과정의 어법(문어체 '~한다')을 따르고,
 * 내용은 이 저장소의 실제 차시(src/data/lessonObjectives.ts)에서 가져온다.
 * 국가 교육과정의 문장을 옮겨 적지 않는다.
 *
 * 차시 묶음(lessonRange)에 적는 범위는 실제 차시 번호와 맞아야 하며
 * `npm run check:curriculum-document`가 이를 강제한다.
 */

export interface ModuleCoreContentItem {
  /** 이 항목이 걸치는 차시 범위 표기. 예: '1~2차시' */
  lessonRange: string;
  /** 묶음의 이름. 표의 왼쪽 열에 온다. */
  title: string;
  /** 문어체 서술 한두 문장. */
  description: string;
}

export interface ModuleCoreContent {
  moduleId: ModuleId;
  /** 이 단원이 무엇을 다루는지 한 문장으로 밝힌 서술. */
  overview: string;
  items: ModuleCoreContentItem[];
  /** 단원 마무리(포트폴리오) 차시가 하는 일. */
  closing: string;
}

