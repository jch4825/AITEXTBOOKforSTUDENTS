/**
 * 고등학교 학년군 전용 심화 수행 과제.
 *
 * 같은 68차시를 중·고가 공통으로 이수하는 편성에서, 지원 수준의 중학과 고등은
 * 그동안 화면 텍스트 밀도와 사실·선택지 각 1개 차이뿐이었다. 학생이 수행하는
 * 과제가 사실상 같아 중학에서 이수한 학생이 고등에서 같은 것을 반복하게 되고,
 * 12학년군 성취기준의 도달을 주장할 근거도 없었다.
 *
 * 이 과제는 같은 이야기와 개념을 쓰되 수행의 요구 수준을 실제로 올린다.
 * 난도는 다음 네 축 중 하나 이상에서 올라간다.
 *  (1) 상황 복잡도 — 조건이 충돌하거나 도중에 바뀐다
 *  (2) 자료 수 — 둘 이상을 교차 대조한다
 *  (3) 독립성 — 촉진 없이 스스로 절차를 세우고 점검한다
 *  (4) 전이 범위 — 교실을 벗어난 실제 상황에 적용한다
 *
 * 제품 계약상 실시간 AI 연결이나 새 이미지를 요구하지 않는다. 준비된 자료와
 * 학생의 판단만으로 완결되어야 한다.
 *
 * 화면에는 지원 수준이 `고등`(challenge)일 때만 전이 단계에서 나타난다.
 */
