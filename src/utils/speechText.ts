/**
 * 화면의 글을 소리 내어 읽기 좋은 글로 바꾼다.
 *
 * 브라우저 읽기는 기기마다 목소리가 달라 기호를 제각각 읽는다. 가운뎃점은 건너뛰어 낱말이
 * 붙어 들리고, 영문 `AI`는 목소리에 따라 글자로 끊거나 `아이`로 읽는다. 읽어 주는 소리가
 * 학습 내용을 바꾸면 안 되므로, 화면에 보이는 글은 그대로 두고 읽는 글에서만 풀어 쓴다.
 *
 * `tts.speak`·`tts.speakSequence`가 모든 읽기 앞에서 부른다. 호출하는 쪽은 화면 글을 그대로 넘긴다.
 * 이 함수는 마크다운을 지우는 `stripForSpeech`보다 먼저 돌아야 한다(strip이 하이픈을 공백으로 바꾼다).
 */
export function toSpeechText(text: string): string {
  return text
    // 나열 사이의 가운뎃점은 쉼표로 풀어 낱말이 붙어 들리지 않게 한다.
    .replace(/[·ㆍ]/g, ', ')
    .replace(/×/g, ' 곱하기 ')
    .replace(/÷/g, ' 나누기 ')
    // 숫자 사이의 하이픈은 빼기다("10000-6600을 계산기에 입력해요"). 범위는 물결(~)로 쓰고,
    // 날짜·전화번호는 이 교과서의 읽는 글에 없다. 그런 글이 생기면 이 규칙을 좁힌다.
    .replace(/(\d)\s*-\s*(\d)/g, '$1 빼기 $2')
    .replace(/\bD-day\b/gi, '디데이')
    // 다른 영문자·숫자에 붙지 않은 AI만 우리말로 읽는다. 앞쪽 경계는 조회로 쓰지 않고 붙잡아 되돌린다.
    // 구형 사파리가 lookbehind 문법 하나 때문에 이 모듈을 통째로 못 읽는 일을 피한다.
    .replace(/(^|[^A-Za-z0-9])AI(?![A-Za-z0-9])/g, '$1에이아이')
    .replace(/\s*,(?:\s*,)+/g, ',')
    .replace(/\s+/g, ' ')
    .replace(/\s+,/g, ',')
    .trim();
}
